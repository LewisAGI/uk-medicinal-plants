test('icon labels show on hover or long-press', async ({ page }, testInfo) => {
  await page.goto('/')
  const button = page.getByRole('button', { name: 'Filters' })
  if (testInfo.project.name === 'desktop' || testInfo.project.name === 'webkit') {
    await button.hover()
  } else {
    await button.dispatchEvent('touchstart', { bubbles: true })
    await page.waitForTimeout(600)
  }
  await expect(page.getByRole('tooltip')).toHaveText('Filters')
})

test('navigation stays inside the viewport', async ({ page }) => {
  await page.goto('/plants/hawthorn')
  const nav = page.getByRole('navigation', { name: 'Primary' })
  const navBox = await nav.boundingBox()
  const heading = page.getByRole('heading', { level: 1, name: 'Hawthorn' })
  const headingBox = await heading.boundingBox()
  const viewport = page.viewportSize()
  expect(navBox).toBeTruthy()
  expect(headingBox).toBeTruthy()
  expect(viewport).toBeTruthy()
  expect(navBox!.x).toBeGreaterThanOrEqual(-1)
  expect(navBox!.y).toBeGreaterThanOrEqual(-1)
  expect(navBox!.x + navBox!.width).toBeLessThanOrEqual(viewport!.width + 1)
  expect(navBox!.y + navBox!.height).toBeLessThanOrEqual(viewport!.height + 1)
  const overlaps = headingBox!.x < navBox!.x + navBox!.width && headingBox!.x + headingBox!.width > navBox!.x && headingBox!.y < navBox!.y + navBox!.height && headingBox!.y + headingBox!.height > navBox!.y
  expect(overlaps).toBe(false)
  await expect(page.locator('.consult')).toContainText('Speak to a pharmacist or doctor')
})

test('built pages reject dosing language and publish headers', async ({ page }) => {
  const headers = readFileSync('dist/_headers', 'utf8')
  expect(headers).toContain('Content-Security-Policy')
  expect(headers).toContain('X-Content-Type-Options: nosniff')
  expect(headers).toContain('Referrer-Policy: no-referrer')
  expect(headers).not.toContain('unsafe-inline')
  const html = readFileSync('dist/index.html', 'utf8')
  expect(html).toMatch(/<script[^>]+src=/)
  expect(html).not.toMatch(/<script(?![^>]*\bsrc=)/)
  expect(html).not.toMatch(/<style[\s>]/)
  expect(html).toMatch(/rel="stylesheet"/)
  expect(readFileSync('dist/_redirects', 'utf8')).toContain('/index.html')
  for (const path of ['/', '/glossary', '/reading', '/plants/meadowsweet', '/plants/foxglove', '/plants/st-johns-wort']) {
    await page.goto(path)
    expect(await bodyText(page), path).not.toMatch(DOSING)
  }
})
