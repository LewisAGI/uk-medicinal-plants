import { readFileSync } from 'node:fs'
import { expect, test, type Page } from '@playwright/test'

const DOSING = /\bmg\b|\bml\b|\bgrams?\b|\bteaspoons?\b|\btimes a day/i

async function bodyText(page: Page) {
  return page.locator('body').innerText()
}

test('catalogue hides unreviewed plants', async ({ page }) => {
  await page.goto('/')
  await expect(page).toHaveTitle('UK medicinal plants')
  await expect(page.getByText('Not medical advice.', { exact: true })).toBeVisible()
  await expect(page.locator('.card')).toHaveCount(45)
  await expect(page.locator('.card-name', { hasText: 'Hawthorn' })).toBeVisible()
  await expect(page.locator('.card-name', { hasText: /^Foxglove$/ })).toHaveCount(0)
  await expect(page.locator('.card-name', { hasText: 'Bluebell' })).toHaveCount(0)
  await expect(page.locator('.card-name', { hasText: /^Holly$/ })).toHaveCount(0)
  await expect(page.getByText('No match for medicinal benefits', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /photo|camera/i })).toHaveCount(0)
  await expect(page.getByRole('link', { name: /photo|camera/i })).toHaveCount(0)
})

test('Latin search opens a graded explanation and the consult banner', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('searchbox', { name: 'Search' }).fill('Hypericum perforatum')
  await page.locator('.card-name', { hasText: "St John's wort" }).click()
  await expect(page).toHaveTitle(/St John's wort/)
  await expect(page.getByRole('heading', { level: 1, name: "St John's wort" })).toBeVisible()
  await expect(page.locator('.latin')).toHaveText('Hypericum perforatum')
  await expect(page.locator('.consult')).toContainText('Speak to a pharmacist or doctor')
  await expect(page.locator('.consult')).toContainText('Not medical advice')
  await expect(page.getByText('Not medical advice.', { exact: true })).toBeVisible()
  await expect(page.locator('.explanation').first()).toContainText('placebo')
  const grade = page.locator('.grade-name').first()
  await expect(grade).toHaveText('Clinically supported (specific products)')
  const gradeBox = await grade.boundingBox()
  const gradeViewport = page.viewportSize()
  expect(gradeBox).toBeTruthy()
  expect(gradeViewport).toBeTruthy()
  expect(gradeBox!.x).toBeGreaterThanOrEqual(-1)
  expect(gradeBox!.x + gradeBox!.width).toBeLessThanOrEqual(gradeViewport!.width + 1)
  const main = await page.locator('main').innerText()
  expect(main.indexOf('contraceptive')).toBeLessThan(main.indexOf('Major depression'))
  await page.getByRole('button', { name: 'Grade definition' }).first().click()
  await expect(page.getByRole('dialog')).toContainText('well-established use')
  await page.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('button', { name: 'Back' }).click()
  await expect(page.getByRole('searchbox', { name: 'Search' })).toHaveValue('Hypericum perforatum')
})

